function [PredY,model] = LUSI_VSVM(TestX,Data,Para)
gam = Para.p1;%kp
tao =Para.p3;
tao1 = 1-Para.p3;
X = Data.X;
Y = Data.Y;
KerX = KerF(X,Para.kpar,X);
KerTstX = KerF(TestX,Para.kpar,X)';
V = Para.V;
P = Para.P;
reg = 0;
if isfield(Para,'reg'), reg = Para.reg; end
Msys = (tao1*V+tao*P)*KerX+(gam+reg)*eye(length(Y));
Ab = inv(Msys)*(tao1*V+tao*P)*Y;
Ac = inv(Msys)*(tao1*V+tao*P)*(ones(length(Y),1));
c = (ones(1,length(Y))*(tao1*V+tao*P)*(Y-KerX*Ab))/(ones(1,length(Y))*(tao1*V+tao*P)*ones(length(Y),1)-ones(1,length(Y))*(tao1*V+tao*P)*KerX*Ac);
A = Ab-c*Ac;
FTrn = (A'*KerX)'+c;%% Y.Trn output
FTst = (A'*KerTstX)'+c;%%Y.test output
thr = 0.5;                              % historical default (see Para.thr)
if isfield(Para,'thr'), thr = Para.thr; end
ftst = FTst-thr;
ftrn = FTrn-thr;
f = (A'*KerTstX)'+c;
PredY.tst = sign(ftst);
PredY.trn = sign(ftrn);
model.alpha = A;
model.w = A'*X;
model.b = c;
model.ftrn = ftrn+0.5;
model.ftst = FTst;
model.P = P;
model.f = f;
model.trnX = Data.X;
model.prob=f;
end
